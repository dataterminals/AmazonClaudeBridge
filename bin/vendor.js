#!/usr/bin/env node
'use strict';
/**
 * vendor.js — generate the copy of the library that the skill injects (Tier 2).
 *
 *   node bin/vendor.js           # rebuild the asset from src/
 *   node bin/vendor.js --check   # fail if the asset is stale (run this in CI)
 *
 * WHY. The skill must never fetch code over the network — that shape gets refused by safety
 * classifiers, correctly, because a mutable `main` means what executes is not knowable at review
 * time. So the fallback path injects a LOCAL copy instead. A local copy that can silently drift
 * from src/ is its own trap, which is what `--check` is for.
 *
 * The transform is deliberately dull: drop whole-line comments and blank lines, nothing else. No
 * identifier mangling, no expression rewriting. This file is executed verbatim inside a page, so
 * a clever minifier's bug would surface as wrong prices rather than as a crash. The saving is
 * real anyway, because the source carries a lot of prose about why Amazon's DOM is the way it is.
 *
 * Any line whose trimmed form starts with `//` is dropped, so never begin a line of real code
 * with a string literal containing a bare `//`. `node --check` and tests/vendor.test.js both run
 * against the output, so a mistake here fails the suite rather than reaching a page.
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const SRC = path.join(ROOT, 'src', 'amazon-claude-bridge.user.js');
const OUT = path.join(ROOT, '.claude', 'skills', 'amazon-shopping', 'assets', 'amzx.min.js');

function build(source) {
  const body = source
    .split('\n')
    .filter((line) => {
      const t = line.trim();
      return t !== '' && !t.startsWith('//');
    })
    .join('\n');
  return '/* Generated by bin/vendor.js from src/amazon-claude-bridge.user.js — do not edit. */\n'
    + body + '\n';
}

// Guarded: tests/vendor.test.js requires this file for build(), and an unguarded main would
// REBUILD the asset on require — so the staleness check would silently pass every time by
// regenerating the very thing it was supposed to be auditing.
function main() {
const built = build(fs.readFileSync(SRC, 'utf8'));

if (process.argv.includes('--check')) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : null;
  if (current !== built) {
    console.error('STALE: ' + path.relative(ROOT, OUT) + ' does not match src/. Run: node bin/vendor.js');
    process.exit(1);
  }
  console.log('vendored asset is in sync with src/');
} else {
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, built, 'utf8');
  const kb = (n) => (n / 1024).toFixed(1) + ' KB';
  console.log('wrote ' + path.relative(ROOT, OUT));
  console.log('  source ' + kb(fs.statSync(SRC).size) + ' -> vendored ' + kb(Buffer.byteLength(built)));
  console.log('  this is spent in context on every page it is injected into — Tier 1 stays preferred.');
}
}

if (require.main === module) main();

module.exports = { build, SRC, OUT };
